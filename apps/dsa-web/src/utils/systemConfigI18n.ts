function normalizeOptionToken(raw: string): string {
  return raw.trim().toLowerCase();
}

export function getCategoryTitle(category: SystemConfigCategory, fallback?: string, _locale: UiLanguage = 'en'): string {
  return categoryTitleMap[category] || fallback || category;
}

export function getCategoryDescription(category: SystemConfigCategory, fallback?: string, _locale: UiLanguage = 'en'): string {
  return categoryDescriptionMap[category] || fallback || '';
}

export function getFieldTitle(key: string, fallback?: string): string {
  return fieldTitleMap[key] || fallback || key;
}

export function getFieldDescription(key: string, fallback?: string): string {
  return fieldDescriptionMap[key] || fallback || '';
}

export function getFieldOptionLabel(
  key: string,
  value: string,
  fallbackLabel?: string,
  _locale: UiLanguage = 'en',
): string {
  const map = fieldOptionLabelMap[key];
  if (!map) {
    return fallbackLabel ?? value;
  }

  const byValue = map[normalizeOptionToken(value)];
  if (byValue) {
    return byValue;
  }

  if (fallbackLabel) {
    const byLabel = map[normalizeOptionToken(fallbackLabel)];
    if (byLabel) {
      return byLabel;
    }
  }

  return fallbackLabel ?? value;
}
